from sqlalchemy import Column, Integer, String, Boolean, DateTime, ForeignKey, Float, Text, Date
from sqlalchemy.orm import relationship
from datetime import datetime, timezone
from app.core.database import Base

class DutyAllocation(Base):
    __tablename__ = "duty_allocations"

    id = Column(Integer, primary_key=True, index=True)
    shift_id = Column(Integer, ForeignKey("examination_shifts.id", ondelete="CASCADE"), nullable=False)
    faculty_id = Column(Integer, ForeignKey("faculty.id", ondelete="CASCADE"), nullable=False)
    
    # Assigned Role: 'JS', 'Reliever', 'Standby', 'SS' (Strictly NO IS category)
    assigned_role = Column(String(50), nullable=False)
    
    # Assigned room or block (for JS), or assigned block range (for Reliever, e.g. "Blocks 1-4")
    assigned_block = Column(String(100), nullable=True)
    
    # Status: Proposed, Approved, Published
    status = Column(String(30), default="Proposed", nullable=False)
    
    # Fairness metrics calculated at time of allocation
    fairness_score = Column(Float, default=0.0)
    prev_js_snapshot = Column(Integer, default=0)
    prev_reliever_snapshot = Column(Integer, default=0)
    prev_standby_snapshot = Column(Integer, default=0)
    prev_total_snapshot = Column(Integer, default=0)
    
    # Human-readable explainable reason generated by the solver
    explainability_reason = Column(Text, nullable=False)
    
    # Audit trail for manual adjustments
    is_manual_override = Column(Boolean, default=False, nullable=False)
    original_role = Column(String(50), nullable=True)
    override_reason = Column(String(255), nullable=True)
    override_by_user = Column(String(100), nullable=True)
    
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc))
    updated_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc))

    shift = relationship("ExaminationShift", back_populates="allocations")
    faculty = relationship("Faculty", back_populates="allocations")

class AllocationConfiguration(Base):
    __tablename__ = "allocation_configurations"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(100), default="Standard Fairness Configuration", nullable=False)
    js_per_classroom = Column(Integer, default=1, nullable=False) # Configurable JS per room (e.g. 1 or 2)
    reliever_ratio = Column(Integer, default=4, nullable=False) # 1 Reliever per X examination blocks
    standby_ratio_or_count = Column(Integer, default=2, nullable=False) # Additional standbys
    
    # Configurable Conflict Rules
    disallow_same_department_js = Column(Boolean, default=False, nullable=False) # Prevent faculty from invigilating own dept exams
    disallow_same_subject_js = Column(Boolean, default=False, nullable=False) # Prevent faculty from invigilating own subject exams
    exclude_ss_from_fairness = Column(Boolean, default=True, nullable=False)
    
    # Solver Multi-Objective Cost Weights
    weight_prev_js = Column(Float, default=2.5, nullable=False)
    weight_prev_reliever = Column(Float, default=2.0, nullable=False)
    weight_prev_standby = Column(Float, default=1.5, nullable=False)
    weight_consecutive = Column(Float, default=2.0, nullable=False)
    weight_dept_equity = Column(Float, default=1.5, nullable=False)
    
    is_active = Column(Boolean, default=True, nullable=False)
    updated_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc))

class AllocationAuditLog(Base):
    __tablename__ = "allocation_audit_logs"

    id = Column(Integer, primary_key=True, index=True)
    action = Column(String(50), nullable=False) # e.g. "MANUAL_ROLE_OVERRIDE", "ALLOCATION_APPROVED", "CONFIG_UPDATED"
    entity_type = Column(String(50), nullable=False) # "DutyAllocation", "Configuration", etc.
    entity_id = Column(Integer, nullable=True)
    faculty_name = Column(String(150), nullable=True)
    performed_by = Column(String(100), nullable=False)
    user_role = Column(String(50), nullable=False)
    details = Column(Text, nullable=False)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc), index=True)

class ManualOverrideRecord(Base):
    __tablename__ = "manual_overrides"

    id = Column(Integer, primary_key=True, index=True)
    shift_id = Column(Integer, ForeignKey("examination_shifts.id", ondelete="CASCADE"), nullable=False)
    original_faculty_id = Column(Integer, ForeignKey("faculty.id", ondelete="SET NULL"), nullable=True)
    replacement_faculty_id = Column(Integer, ForeignKey("faculty.id", ondelete="SET NULL"), nullable=True)
    original_role = Column(String(50), nullable=False)
    new_role = Column(String(50), nullable=False)
    override_reason = Column(String(255), nullable=False)
    impact_warning = Column(Text, nullable=True)
    performed_by = Column(String(100), nullable=False)
    timestamp = Column(DateTime, default=lambda: datetime.now(timezone.utc), index=True)
